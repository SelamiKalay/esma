Object.keys(ESMA_ICERIK).forEach((k) => {
  if (!/^\d+$/.test(k) && !ESMA_LISTESI.some((e) => e[2] === k)) console.error("Bilinmeyen içerik anahtarı:", k);
});

const RENKLER = ["#1F4E5F", "#1F6F5C", "#6B3E5E", "#2E4A7D", "#7A4B22", "#3D5A3A", "#5B3F7A", "#7D2E3B", "#2F5D62"];

const ESMALAR = ESMA_LISTESI.map(([arapca, okunus, slug, anlam_kisa], i) => {
  const sira = i + 1;
  const icerik = ESMA_ICERIK[sira] || ESMA_ICERIK[slug] || null;
  return {
    sira,
    slug,
    arapca,
    okunus,
    anlam_kisa,
    renk: RENKLER[i % RENKLER.length],
    ...(icerik || {}),
    // Ayet metni elle yazılmaz; tools/ayet-getir.js'in kaynaktan ürettiği veri/ayetler.js'den gelir.
    ...(icerik && typeof AYET_METINLERI !== "undefined" ? { ayet: AYET_METINLERI[slug] } : {}),
    hazir: Boolean(icerik),
  };
});

if (ESMALAR.length !== 99) console.error("Esma sayısı 99 olmalı, şu an:", ESMALAR.length);
